const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const req = require('node:module').createRequire(path.resolve('frontend/package.json'));
const { JSDOM } = req('jsdom');
let amdCalls = 0;
const define = () => { amdCalls++; };
define.amd = {};
const dom = new JSDOM('<!doctype html><html><body></body></html>', {runScripts:'outside-only'});
const context = dom.window;
context.define = define;
context.structuredClone = structuredClone;
context.eval(fs.readFileSync('frontend/public/mermaid.min.js','utf8'));
assert.equal(context.define, define, 'Mermaid must preserve the Monaco AMD loader');
assert.equal(amdCalls, 0, 'Mermaid must not register with the Monaco AMD loader');
assert.equal(typeof context.mermaid?.initialize, 'function');
context.define('vs/editor/editor.main.nls', [], () => ({}));
assert.equal(amdCalls, 1, 'Monaco language modules can still call define');
const viewer = fs.readFileSync('frontend/src/components/MarkdownViewer.tsx','utf8');
assert.ok(!/\(window as any\)\.define\s*=/.test(viewer), 'Async loader must never clear global define');
console.log('PASS: real Mermaid bundle loads globally while Monaco AMD remains callable');
dom.window.close();
