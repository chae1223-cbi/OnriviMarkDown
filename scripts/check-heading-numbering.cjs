const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
const req = require('node:module').createRequire(path.resolve('frontend/package.json'));
const ts = req('typescript');
const cache = {};
function load(name) {
  if (cache[name]) return cache[name];
  const code = ts.transpileModule(fs.readFileSync(path.resolve('frontend/src/lib', name + '.ts'), 'utf8'), { compilerOptions: { module: 1, target: 7 } }).outputText;
  const exports = cache[name] = {};
  new Function('require', 'exports', code)(id => id.startsWith('./') ? load(id.slice(2)) : req(id), exports);
  return exports;
}
const api = load('headingNumbering');
const formats = ['roman', 'decimal', 'hangul', 'decimal-paren', 'hangul-paren', { type: 'custom', number: 'bullet', prefix: '', suffix: '', bullet: '◆' }];
const source = '---\r\ntitle: 제목\r\n---\r\n\r\n# 첫 제목\r\n\r\n## **하위** 제목\r\n\r\n###### 기호 제목\r\n\r\n###### 다음 기호\r\n\r\n```md\r\n# 코드 속 제목\r\n```\r\n\r\n    # 들여쓴 코드\r\n\r\n본문은 그대로\r\n\r\n# 둘째 제목';
const numbered = api.syncMarkdownHeadingNumbers(source, formats);
assert.ok(numbered.includes('# Ⅰ. 첫 제목\r\n'));
assert.ok(numbered.includes('## 1. **하위** 제목\r\n'));
assert.ok(numbered.includes('###### ◆ 기호 제목\r\n'));
assert.ok(numbered.includes('###### ◆ 다음 기호\r\n'));
assert.ok(numbered.endsWith('# Ⅱ. 둘째 제목'));
assert.ok(numbered.includes('```md\r\n# 코드 속 제목\r\n```'));
assert.ok(numbered.includes('    # 들여쓴 코드'));
assert.ok(numbered.startsWith('---\r\ntitle: 제목\r\n---'));
assert.equal(api.syncMarkdownHeadingNumbers(numbered, formats), numbered, 'Repeated synchronization must not duplicate labels');
assert.equal(api.syncMarkdownHeadingNumbers(numbered, [], formats), source, 'Disabling removes labels while preserving source');
const custom = [{ type: 'custom', number: 'decimal', prefix: '제', suffix: '장' }];
assert.equal(api.syncMarkdownHeadingNumbers('# Ⅱ. 제목\n\n# 다음', custom), '# 제1장 제목\n\n# 제2장 다음');
assert.equal(api.syncMarkdownHeadingNumbers('# 제1장 제목', formats, custom), '# Ⅰ. 제목');
assert.equal(api.syncMarkdownHeadingNumbers('제목\n====\n\n하위\n----', formats), 'Ⅰ. 제목\n====\n\n1. 하위\n----');
assert.equal(api.headingMarker(formats[5], 99), '◆');
const { EditorState } = req('prosemirror-state'), { defaultMarkdownParser } = req('prosemirror-markdown');
const state = EditorState.create({ doc: defaultMarkdownParser.parse('# 제목\n\n## **강조** 제목\n\n###### 기호') });
const tr = api.numberHeadingTransaction(state.tr, formats);
const headings = [];
tr.doc.descendants(node => { if (node.type.name === 'heading') headings.push(node.textContent); });
assert.deepEqual(headings, ['Ⅰ. 제목', '1. 강조 제목', '◆ 기호']);
assert.ok(tr.doc.child(1).content.content.some(node => node.marks.some(mark => mark.type.name === 'strong')), 'Title emphasis must survive prefix edits');
assert.equal(api.numberHeadingTransaction(EditorState.create({ doc: tr.doc }).tr, formats).docChanged, false);
console.log('PASS: source synchronization, bullets, format changes/removal, CRLF, frontmatter/code preservation, setext and marked heading transactions.');
const cleaner = load('../utils/markdownCleaner');
const pastedSource = '# 기존 제목\n\n' + '# 99. 붙여넣은 제목\n\n## 하위 제목\n\n###### 기호 제목\n\n###공백누락 제목\n\n```md\n# 코드 제목\n```\n\n| A | B |\n|---|---|\n| 값1 | 값2 |';
const afterPaste = api.syncMarkdownHeadingNumbers(pastedSource, formats);
assert.ok(afterPaste.includes('# Ⅱ. 붙여넣은 제목'));
assert.ok(afterPaste.includes('## 1. 하위 제목'));
assert.ok(afterPaste.includes('###### ◆ 기호 제목'));
const afterCleanup = api.syncMarkdownHeadingNumbers(cleaner.cleanMarkdownDocument(afterPaste).cleanedText, formats);
assert.ok(afterCleanup.includes('### 가. 공백누락 제목'));
assert.ok(afterCleanup.includes('# Ⅱ. 붙여넣은 제목'));
assert.ok(afterCleanup.includes('###### ◆ 기호 제목'));
assert.ok(afterCleanup.includes('```md\n# 코드 제목\n```'));
assert.ok(afterCleanup.includes('값1') && afterCleanup.includes('값2'));
assert.equal(api.syncMarkdownHeadingNumbers(cleaner.cleanMarkdownDocument(afterCleanup).cleanedText, formats), afterCleanup);
console.log('PASS: source-editor paste and document cleanup pipeline renumbers repaired headings, preserves bullets/code/table and is repeatable.');
