import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
import mammoth from 'mammoth';
import {JSDOM} from 'jsdom';
import {pathToFileURL} from 'node:url';
import {createRequire} from 'node:module';
const dom=new JSDOM(''); globalThis.DOMParser=dom.window.DOMParser;
const source=ts.transpileModule(fs.readFileSync(new URL('../src/lib/importHtmlMarkdown.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {htmlToImportMarkdown}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const fixture=htmlToImportMarkdown('<p><strong>• </strong>first</p><p><strong>• </strong>second</p><p><strong> label </strong>를</p>');
assert(fixture.includes('- first\n- second')); assert(!fixture.includes('**• **'));
assert(fixture.includes('**label**'));
assert(!fixture.includes('<strong>'));
assert.equal(htmlToImportMarkdown('<figure><img src="/media/a.png"><figcaption>caption</figcaption></figure>'),'![caption](</media/a.png>)');
assert(!htmlToImportMarkdown('<figure><img src="javascript:evil()" onerror="evil()"><figcaption>caption</figcaption></figure>').includes('evil()'));
if(process.argv[2]) {
  const require=createRequire(import.meta.url);
  const sizesSource=ts.transpileModule(fs.readFileSync(new URL('../src/lib/docxImageSizes.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText.replace("'jszip'",JSON.stringify(pathToFileURL(require.resolve('jszip')).href));
  const {readDocxImageSizes}=await import('data:text/javascript;base64,'+Buffer.from(sizesSource).toString('base64'));
  const bytes=fs.readFileSync(process.argv[2]);
  const sizes=await readDocxImageSizes(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength));
  const widths=[...sizes.values()].flat();
  assert.equal(widths.length,7);
  assert.equal(widths.filter(w=>w===567).length,6);
  assert(widths.includes(335));
  const result=await mammoth.convertToHtml({buffer:fs.readFileSync(process.argv[2])},{styleMap:["p[style-name='Caption'] => figcaption:fresh"]});
  const md=htmlToImportMarkdown(result.value);
  const {marked}=await import('marked');
  const doc=new JSDOM(marked.parse(md)).window.document;
  assert.equal(doc.images.length,7);
  assert.equal(doc.querySelectorAll('figure').length,0);
  assert.equal(Array.from(doc.images).filter(img=>img.alt).length,6);
  assert.equal(doc.querySelectorAll('table').length,1);
  assert(doc.querySelectorAll('ul').length>0); assert(doc.querySelectorAll('ol').length>0);
  assert(!doc.body.textContent.includes('**• **'));
  assert(doc.querySelector('strong'));
  console.log(JSON.stringify({images:doc.images.length,captions:doc.querySelectorAll('figcaption').length,lists:doc.querySelectorAll('ul,ol').length,headings:doc.querySelectorAll('h1,h2,h3,h4').length}));
}
console.log('DOCX import checks passed');
