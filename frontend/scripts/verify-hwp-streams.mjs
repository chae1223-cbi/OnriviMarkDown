import fs from 'node:fs';
import assert from 'node:assert/strict';
import {deflateRawSync,inflateRawSync} from 'node:zlib';
import ts from 'typescript';
const code=ts.transpileModule(fs.readFileSync(new URL('../src/lib/hwpStreams.ts',import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {readHwpCompression,decodeHwpBody,decodeHwpParagraph}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const header=new Uint8Array(256);header.set(Buffer.from('HWP Document File'));
const body=Buffer.from('한글 본문','utf16le');
assert.equal(readHwpCompression(header),false);
assert.equal(decodeHwpBody(body,false,()=>{throw new Error('must not inflate');}),body);
header[36]=1;assert.equal(readHwpCompression(header),true);
assert.deepEqual(Buffer.from(decodeHwpBody(deflateRawSync(body),true,data=>inflateRawSync(data))),body);
assert.throws(()=>decodeHwpBody(Buffer.from('corrupt'),true,data=>inflateRawSync(data)));
header[36]=2;assert.throws(()=>readHwpCompression(header),/암호/);
header[36]=4;assert.throws(()=>readHwpCompression(header),/배포용/);
assert.throws(()=>readHwpCompression(new Uint8Array(5)),/손상/);
const inline=Buffer.alloc(16);inline.writeUInt16LE(9,0);inline.writeUInt16LE(9,14);
assert.equal(decodeHwpParagraph(Buffer.concat([Buffer.from('앞','utf16le'),inline,Buffer.from('뒤','utf16le')])),'앞\t뒤');
assert.equal(decodeHwpParagraph(Buffer.from([30,0,...Buffer.from('프로그램','utf16le'),24,0,...Buffer.from('설치','utf16le')])),' 프로그램-설치');
