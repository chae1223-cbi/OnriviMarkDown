import fs from 'node:fs';
import assert from 'node:assert/strict';
import ts from 'typescript';
import JSZip from 'jszip';
import {JSDOM} from 'jsdom';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
globalThis.DOMParser=new JSDOM('').window.DOMParser;
const require=createRequire(import.meta.url);
const url=s=>'data:text/javascript;base64,'+Buffer.from(s).toString('base64');
const compile=name=>ts.transpileModule(fs.readFileSync(new URL('../src/lib/'+name,import.meta.url),'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const source=compile('epubImporter.ts').replace("'jszip'",JSON.stringify(pathToFileURL(require.resolve('jszip')).href)).replace("'./importHtmlMarkdown'",JSON.stringify(url(compile('importHtmlMarkdown.ts'))));
const {importEpub}=await import(url(source));
const {htmlToImportMarkdown}=await import(url(compile('importHtmlMarkdown.ts')));
const quote=htmlToImportMarkdown('<blockquote>\n<p><span class="onrivi-line">first</span><br><span class="onrivi-line">second</span></p>\n</blockquote>');
assert.equal(quote,'> first  \n> second');
const code=htmlToImportMarkdown('<div class="codeblock-area"><div class="codeblock-header">text</div><pre><code class="language-text"><span class="onrivi-line">first</span><span class="onrivi-line">\u200b</span><span class="onrivi-line">second</span></code></pre></div>');
assert.equal(code,'```text\nfirst\n\nsecond\n```');
const zip=new JSZip();
zip.file('META-INF/container.xml','<container><rootfile full-path="OEBPS/book.opf"/></container>');
zip.file('OEBPS/book.opf','<p:package xmlns:p="urn:epub"><p:manifest><p:item id="a" href="a.xhtml"/><p:item id="b" href="b.xhtml"/></p:manifest><p:spine><p:itemref idref="b"/><p:itemref idref="a"/></p:spine></p:package>');
zip.file('OEBPS/a.xhtml','<h1>Second</h1><img src="images/a.png"/><img src="data:image/png;base64,YQ=="/>');
zip.file('OEBPS/b.xhtml','<h1>First</h1><p><strong>bold</strong></p><img src="images/a.png"/>');
zip.file('OEBPS/images/a.png','image');
const buffer=await zip.generateAsync({type:'arraybuffer'});
let saves=0;
const md=await importEpub(buffer,async()=>`/media/test${++saves}.png`);
assert(md.indexOf('# First')<md.indexOf('# Second'));
assert.equal(saves,2);
assert(!md.includes('base64'));
assert(md.includes('**bold**'));
await assert.rejects(()=>importEpub(buffer),/공통 자원 폴더/);
if(process.argv[2]) {
 const bytes=fs.readFileSync(process.argv[2]);let images=0;
 const output=await importEpub(bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength),async()=>`/media/sample${++images}.png`);
 assert(output.length>100);assert(!output.includes('data:image'));
 console.log(JSON.stringify({chars:output.length,savedImages:images}));
}
console.log('EPUB import checks passed');
