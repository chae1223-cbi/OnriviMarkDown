import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
const values=new Map();
globalThis.localStorage={getItem:k=>values.get(k)??null,setItem:(k,v)=>values.set(k,v),removeItem:k=>values.delete(k)};
globalThis.window={dispatchEvent:()=>{}};
globalThis.CustomEvent=class { constructor(type,options){this.type=type;this.detail=options?.detail;} };
const source=fs.readFileSync(new URL('../src/lib/resourceSettings.ts',import.meta.url),'utf8');
const code=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const {getResourceEnvironment,getResourceSettings,saveResourceSettings,activateDriveAccount}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
values.set('workspaceType','browser');values.set('onrivi_last_workspace_mode','cloud');
assert.equal(getResourceEnvironment(),'cloud');
const drive={kind:'drive',path:'参照',folderId:'selected-id'};
saveResourceSettings(drive,'cloud');
values.set('workspaceType','local');values.set('onrivi_last_workspace_mode','local');
assert.equal(getResourceEnvironment(),'cloud');assert.equal(getResourceSettings().folderId,'selected-id');
saveResourceSettings({kind:'browser',path:'Local Assets'},'local');
assert.equal(getResourceEnvironment(),'local');assert.equal(getResourceSettings().path,'Local Assets');
assert.equal(getResourceSettings('cloud').folderId,'selected-id');
saveResourceSettings(drive,'cloud',{silent:true});assert.equal(getResourceEnvironment(),'local');
console.log('PASS: selected resource storage independent of workspace, explicit local switch, cloud selection retained, background update does not switch destination');
values.set('onrivi_gdrive_workspace_info',JSON.stringify({userEmail:'a@example.com',resourceFolderId:'selected-id',workspaceFolderId:'workspace-a'}));
activateDriveAccount('b@example.com');
assert.equal(getResourceSettings('cloud'),null);
assert.equal(values.has('onrivi_gdrive_workspace_info'),false);
saveResourceSettings({kind:'drive',path:'New account resources',folderId:'resource-b'},'cloud');
values.set('onrivi_gdrive_workspace_info',JSON.stringify({userEmail:'b@example.com',resourceFolderId:'resource-b',workspaceFolderId:'workspace-b'}));
activateDriveAccount('a@example.com');
assert.equal(getResourceSettings('cloud').folderId,'selected-id');
assert.equal(JSON.parse(values.get('onrivi_gdrive_workspace_info')).workspaceFolderId,'workspace-a');
activateDriveAccount('b@example.com');
assert.equal(getResourceSettings('cloud').folderId,'resource-b');
assert.equal(JSON.parse(values.get('onrivi_gdrive_workspace_info')).workspaceFolderId,'workspace-b');
console.log('PASS: first account connection ignores previous folder IDs, account A/B settings restored independently');
saveResourceSettings(null,'local');
assert.equal(getResourceSettings('local'),null);
assert.equal(getResourceSettings('cloud').folderId,'resource-b');
values.clear();assert.equal(getResourceSettings('local'),null);
console.log('PASS: cleared/missing local settings stay unset without invented OS paths');
const local={kind:'local',path:'D:/SelectedAssets'};
saveResourceSettings(local,'local');
for(let cycle=0;cycle<3;cycle++) {
  saveResourceSettings(drive,'cloud');
  saveResourceSettings(local,'local',{silent:true});
  assert.equal(values.get('resourceFolder'),drive.path);
  assert.equal(getResourceSettings('local').path,local.path);
  saveResourceSettings(getResourceSettings('local'),'local');
  saveResourceSettings(drive,'cloud',{silent:true});
  assert.equal(values.get('resourceFolder'),local.path);
  assert.equal(getResourceEnvironment(),'local');
  assert.equal(getResourceSettings().path,local.path);
}
console.log('PASS: repeated local/Drive/local transitions retain selected paths and ignore inactive background aliases');
